// „acum 3 zile” / „3 days ago”, după o dată ISO (aceleași praguri ca lib/prospectare/afisare.ts).
export function vechime(iso: string, locale: Locale, acum: number = Date.now()): string {
  const ro = locale === "ro";
  const ms = acum - new Date(iso).getTime();
  if (!Number.isFinite(ms) || ms < 0) return ro ? "acum" : "just now";
  const minute = Math.floor(ms / 60_000);
  if (minute < 2) return ro ? "acum un minut" : "a minute ago";
  if (minute < 60) return ro ? `acum ${minute} minute` : `${minute} minutes ago`;
  const ore = Math.floor(minute / 60);
  if (ore < 24) return ro ? (ore === 1 ? "acum o oră" : `acum ${ore} ore`) : ore === 1 ? "an hour ago" : `${ore} hours ago`;
  const zile = Math.floor(ore / 24);
  if (zile === 1) return ro ? "ieri" : "yesterday";
  if (zile < 14) return ro ? `acum ${zile} zile` : `${zile} days ago`;
  const saptamani = Math.floor(zile / 7);
  if (saptamani < 9) return ro ? `acum ${saptamani} săptămâni` : `${saptamani} weeks ago`;
  const luni = Math.floor(zile / 30);
  return ro ? `acum ${luni} luni` : `${luni} months ago`;
}

// Starea unui termen (YYYY-MM-DD) față de „azi” (aceleași reguli ca stareTermen din lib/prospectare/afisare.ts).
export function termenText(termenIso: string | null, azi: string, locale: Locale): { text: string; intarziat: boolean; azi: boolean } | null {
  if (!termenIso) return null;
  const ro = locale === "ro";
  const zile = Math.round((new Date(`${termenIso.slice(0, 10)}T12:00:00`).getTime() - new Date(`${azi.slice(0, 10)}T12:00:00`).getTime()) / 86_400_000);
  if (zile < 0) return { text: ro ? `întârziat cu ${-zile} ${-zile === 1 ? "zi" : "zile"}` : `${-zile} ${-zile === 1 ? "day" : "days"} overdue`, intarziat: true, azi: false };
  if (zile === 0) return { text: ro ? "azi" : "today", intarziat: false, azi: true };
  if (zile === 1) return { text: ro ? "mâine" : "tomorrow", intarziat: false, azi: false };
  return { text: ro ? `peste ${zile} zile` : `in ${zile} days`, intarziat: false, azi: false };
}

