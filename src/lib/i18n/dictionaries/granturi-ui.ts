// Formatări dependente de limbă (numere, monede, date).
export function formatariGranturi(locale: Locale) {
  const nf = locale === "ro" ? "ro-RO" : "en-GB";
  const formatData = (iso: string | null) => (iso ? new Date(`${iso}T00:00:00`).toLocaleDateString(nf, { day: "numeric", month: "short", year: "numeric" }) : "—");
  const formatSuma = (n: number | null, moneda: string) => (n === null ? "—" : new Intl.NumberFormat(nf, { style: "currency", currency: moneda, maximumFractionDigits: 0 }).format(n));
  const formatSume = (pe: Record<string, number>) => {
    const e = Object.entries(pe);
    return e.length ? e.map(([m, n]) => formatSuma(n, m)).join(" · ") : "—";
  };
  const dataLunga = (d: Date) => d.toLocaleDateString(nf, { day: "numeric", month: "long", year: "numeric" });
  return { formatData, formatSuma, formatSume, dataLunga };
}

