// Rândurile calculate de lib/analiza-donator.ts vin în română (motivul riscului, eticheta, ritmul); aici le redăm în engleză
// pe baza tiparelor lor, ca să nu atingem biblioteca comună.
export function riscMotivEn(text: string): string {
  const m = (re: RegExp) => text.match(re);
  if (text === "Fără donații înregistrate.") return "No donations recorded.";
  if (text === "Donează constant și e la zi cu ritmul lui.") return "Gives consistently and is on track with their rhythm.";
  let r = m(/^A întârziat: a trecut de ~([\d.,]+)× ritmul lui obișnuit\. Merită un contact\.$/);
  if (r) return `Running late: past ~${r[1].replace(",", ".")}× their usual rhythm. Worth a contact.`;
  r = m(/^Mult peste ritm \(~(\d+)× intervalul lui\): probabil pierdut\. Reactivare urgentă\.$/);
  if (r) return `Far beyond their rhythm (~${r[1]}× their interval): probably lost. Urgent reactivation.`;
  r = m(/^Donator unic, recent \(acum ~(\d+) luni\): poate fi transformat în donator recurent\.$/);
  if (r) return `One-time donor, recent (~${r[1]} months ago): can be turned into a recurring donor.`;
  r = m(/^Donator unic, rece de ~(\d+) luni: a donat o singură dată\.$/);
  if (r) return `One-time donor, cold for ~${r[1]} months: gave only once.`;
  return text;
}

const ETICHETE_RISC_EN: Record<string, string> = {
  Fidel: "Loyal",
  "În întârziere": "Overdue",
  "La risc": "At risk",
  "Donator unic": "One-time donor",
  "Unic, rece": "One-time, cold",
  "Fără donații": "No donations",
};

export function etichetaRiscEn(text: string): string {
  return ETICHETE_RISC_EN[text] ?? text;
}

export function ritmEn(text: string): string {
  if (text === "o singură donație") return "a single donation";
  if (text === "o donație pe an (aproximativ)") return "about one donation a year";
  let r = text.match(/^o donație la ~(\d+) zile$/);
  if (r) return `one donation every ~${r[1]} days`;
  r = text.match(/^o donație la ~(\d+) luni$/);
  if (r) return `one donation every ~${r[1]} months`;
  r = text.match(/^o donație la ~([\d.,]+) ani$/);
  if (r) return `one donation every ~${r[1].replace(",", ".")} years`;
  return text;
}
