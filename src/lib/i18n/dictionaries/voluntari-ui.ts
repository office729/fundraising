// Eticheta unei săptămâni din lista de campanii (src/lib/voluntari-panou.ts: „Săptămâna aceasta · 02.11 – 06.11”); în engleză se înlocuiește doar începutul.
export function traduEticheteSaptamana(locale: Locale, eticheta: string): string {
  if (locale === "ro") return eticheta;
  const d = VOLUNTARI_UI_DICT.en.saptamana;
  return eticheta.replace(/^Săptămâna aceasta/, d.aceasta).replace(/^Săptămâna viitoare/, d.viitoare).replace(/^Săptămâna/, d.alta);
}
