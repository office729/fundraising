// Traduce eroarea de validare legată de un câmp (valideazaPropunere întoarce texte românești, pe câmp).
export function traduEroareCamp(locale: Locale, camp: string, mesaj: string): string {
  if (locale === "ro") return mesaj;
  const e = INOVARE_UI_DICT.en.erori;
  if (mesaj.includes("pare să conțină")) {
    const tip = mesaj.includes("email") ? "email" : mesaj.includes("telefon") ? "telefon" : "cnp";
    return e.datePersonale(e.ce[tip]!);
  }
  if (camp === "titlu") return e.titluMin;
  if (camp === "descriere") return e.descriereMin;
  if (camp === "categorie") return e.categorie;
  if (camp === "obiectiv") return e.obiectiv;
  if (camp === "frecventa") return e.frecventa;
  return mesaj;
}

export function traduMesajServer(locale: Locale, mesaj: string): string {
  return locale === "ro" ? mesaj : (INOVARE_UI_DICT.en.mesajeServer[mesaj] ?? mesaj);
}

export type { DictInovare };
