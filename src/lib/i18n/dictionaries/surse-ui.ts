// Etichetă de sursă pentru rapoarte (în engleză doar cele două valori speciale; numele platformelor sunt aceleași).
export function etichetaSursaTr(locale: Locale, sursa: string, fallback: (s: string) => string): string {
  if (locale === "ro") return fallback(sursa);
  return SURSE_UI_DICT.en.surse[sursa] ?? fallback(sursa);
}

// Etichetele de atribuire din rapoarte vin din bibliotecă ca „sursă · etichetă canal în română”; în engleză se înlocuiește eticheta canalului.
export function traduEtichetaAtribuire(locale: Locale, text: string): string {
  if (locale === "ro") return text;
  const i = text.lastIndexOf(" · ");
  if (i < 0) return text;
  const canalRo = text.slice(i + 3);
  const cheie = Object.entries(SURSE_UI_DICT.ro.canal).find(([, v]) => v === canalRo)?.[0];
  const sursa = text.slice(0, i);
  return `${SURSE_UI_DICT.en.surse[sursa] ?? sursa} · ${cheie ? SURSE_UI_DICT.en.canal[cheie] : canalRo}`;
}

// Mesajele de eroare ale generatorului de linkuri (src/lib/atribuire/linkuri.ts) sunt în română în bibliotecă; în engleză se potrivesc pe formă.
export function traduEroareLink(locale: Locale, mesaj: string): string {
  if (locale === "ro") return mesaj;
  const e = SURSE_UI_DICT.en.erori.campGol;
  if (mesaj === "Alege pagina către care trimiți.") return SURSE_UI_DICT.en.generator.alegePagina;
  if (mesaj.startsWith("Adresa paginii trebuie")) return "The page address must start with https://.";
  if (mesaj.startsWith("Identificatorul postării")) return "Post or ad identifier: use only lowercase letters, digits and . _ : - (for example post_03).";
  const gol = mesaj.match(/^(.+): completează câmpul\.$/);
  if (gol) return `${e[gol[1]!] ?? gol[1]}: fill in this field.`;
  const cod = mesaj.match(/^(.+): folosește doar litere mici/);
  if (cod) return `${e[cod[1]!] ?? cod[1]}: use only lowercase letters, digits and . _ : - (for example christmas_2026), with no spaces, diacritics or people's names.`;
  return mesaj;
}

